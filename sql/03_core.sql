-- add_jwt_claims(json,int)
CREATE OR REPLACE FUNCTION sec.add_jwt_claims(payload json, duration_seconds integer DEFAULT 300)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'pgsodium','pg_catalog','public'
AS $$
DECLARE
  now_epoch BIGINT := FLOOR(EXTRACT(EPOCH FROM NOW()));
  out json;
BEGIN
  out := COALESCE(payload, '{}'::json);
  out := out::jsonb || jsonb_build_object(
    'iat', now_epoch,
    'nbf', now_epoch,
    'exp', (now_epoch + greatest(0,duration_seconds))
  );
  RETURN out::json;
END;
$$;
ALTER FUNCTION sec.add_jwt_claims(payload json, duration_seconds integer) OWNER TO pgsodium_admin;

-- base64url_encode(bytea)
CREATE OR REPLACE FUNCTION sec.base64url_encode(data bytea)
RETURNS text
LANGUAGE sql IMMUTABLE
AS $$
  SELECT replace(replace(rtrim(regexp_replace(encode($1,'base64'), E'[\\r\\n]+','','g'),'='),'+','-'),'/','_');
$$;
ALTER FUNCTION sec.base64url_encode(data bytea) OWNER TO sec_owner;

-- base64url(jsonb)
CREATE OR REPLACE FUNCTION sec.base64url(json_in jsonb)
RETURNS text
LANGUAGE sql IMMUTABLE
AS $$
  SELECT sec.base64url_encode(convert_to($1::text,'utf8'));
$$;
ALTER FUNCTION sec.base64url(json_in jsonb) OWNER TO sec_owner;

-- derive_eddsa_privkey(int)
CREATE OR REPLACE FUNCTION sec.derive_eddsa_privkey(key_id integer)
RETURNS bytea
LANGUAGE sql SECURITY DEFINER
SET search_path TO 'pgsodium','pg_catalog','public'
AS $$
  SELECT secret
  FROM pgsodium.crypto_sign_seed_new_keypair(pgsodium.derive_key(key_id));
$$;
ALTER FUNCTION sec.derive_eddsa_privkey(key_id integer) OWNER TO pgsodium_admin;

-- derive_eddsa_pubkey(int)
CREATE OR REPLACE FUNCTION sec.derive_eddsa_pubkey(key_id integer)
RETURNS bytea
LANGUAGE sql SECURITY DEFINER
SET search_path TO 'sec','public'
AS $$
  SELECT public
  FROM pgsodium.crypto_sign_seed_new_keypair(pgsodium.derive_key(key_id));
$$;
ALTER FUNCTION sec.derive_eddsa_pubkey(key_id integer) OWNER TO sec_owner;

-- export_eddsa_jwk(int, text)  (utile per pubblicare JWKS a PostgREST)
CREATE OR REPLACE FUNCTION sec.export_eddsa_jwk(keypair_id integer, kid text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'sec','public'
AS $$
DECLARE
  pk bytea;
  x_b64 text;
  kid_eff text := COALESCE(kid, 'ed25519-' || keypair_id::text);
BEGIN
  pk := sec.derive_eddsa_pubkey(keypair_id);
  x_b64 := sec.base64url_encode(pk);
  RETURN jsonb_build_object(
    'kty','OKP',
    'crv','Ed25519',
    'x',  x_b64,
    'kid',kid_eff,
    'use','sig',
    'alg','EdDSA'
  );
END;
$$;
ALTER FUNCTION sec.export_eddsa_jwk(keypair_id integer, kid text) OWNER TO sec_owner;

-- sign_jwt_eddsa(jsonb, int, int)
CREATE OR REPLACE FUNCTION sec.sign_jwt_eddsa(jwt jsonb, p_expires_in_seconds integer, keypair_id integer DEFAULT 2)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'sec','public'
AS $$
DECLARE
  kid text := 'ed25519-' || keypair_id::text;
  header_json  jsonb;
  payload_json jsonb;
  b64header text;
  b64payload text;
  signing_input text;
  sk bytea;
  sig bytea;
  b64sig text;
BEGIN
  payload_json := (sec.add_jwt_claims(jwt::json, p_expires_in_seconds))::jsonb;
  header_json  := jsonb_build_object('alg','EdDSA','typ','JWT','kid', kid);

  b64header  := sec.base64url(header_json);
  b64payload := sec.base64url(payload_json);
  signing_input := b64header || '.' || b64payload;

  sk := sec.derive_eddsa_privkey(keypair_id);
  sig := pgsodium.crypto_sign_detached(convert_to(signing_input,'utf8'), sk);
  b64sig := sec.base64url_encode(sig);

  -- hardening (whitespace unlikely ma innocuo)
  b64header  := regexp_replace(b64header,  '\s', '', 'g');
  b64payload := regexp_replace(b64payload, '\s', '', 'g');
  b64sig     := regexp_replace(b64sig,     '\s', '', 'g');

  RETURN b64header || '.' || b64payload || '.' || b64sig;
END;
$$;
ALTER FUNCTION sec.sign_jwt_eddsa(jwt jsonb, p_expires_in_seconds integer, keypair_id integer) OWNER TO pgsodium_admin;

